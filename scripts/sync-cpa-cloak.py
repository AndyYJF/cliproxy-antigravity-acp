#!/usr/bin/env python3
"""Sync the official stable CPA matcher verbatim, changing only its config import."""
import argparse
import hashlib
import json
import os
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO = "router-for-me/CLIProxyAPI"
DEST = ROOT / "internal/cpacloak"
SOURCE = "internal/runtime/executor/helps/cloak_obfuscate.go"
TEST = "internal/runtime/executor/helps/cloak_obfuscate_test.go"
CONFIG = "internal/config/config_types.go"
DEPS = ("github.com/MoeForge/moego", "github.com/sirupsen/logrus")

def api(path):
    headers = {"Accept": "application/vnd.github+json"}
    if os.environ.get("GH_TOKEN"):
        headers["Authorization"] = "Bearer " + os.environ["GH_TOKEN"]
    req = urllib.request.Request("https://api.github.com/repos/" + REPO + "/" + path, headers=headers)
    with urllib.request.urlopen(req, timeout=40) as response:
        return json.load(response)

def fetch(commit, path):
    with urllib.request.urlopen("https://raw.githubusercontent.com/" + REPO + "/" + commit + "/" + path, timeout=40) as response:
        return response.read().decode()

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--tag")
    args = parser.parse_args()
    tag = args.tag or api("releases/latest")["tag_name"]
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        raise SystemExit("Only official stable version tags are accepted")
    commit = api("commits/" + tag)["sha"]
    files = {p: fetch(commit, p) for p in (SOURCE, TEST, CONFIG, "go.mod", "LICENSE")}
    rule = re.search(r"(?ms)^type SensitivePatternRule struct \{.*?^\}", files[CONFIG])
    if not rule:
        raise SystemExit("CPA rule structure changed; current implementation was not replaced")
    dependencies = {}
    for name in DEPS:
        match = re.search(r"(?m)^\s*" + re.escape(name) + r"\s+(\S+)", files["go.mod"])
        if not match:
            raise SystemExit("CPA dependency changed: " + name)
        dependencies[name] = match.group(1)
    manifest = {
        "repository": REPO, "tag": tag, "commit": commit,
        "sources": {p: hashlib.sha256(files[p].encode()).hexdigest() for p in (SOURCE, TEST)},
        "rule_sha256": hashlib.sha256(rule.group().encode()).hexdigest(),
        "dependencies": dependencies,
    }
    previous_path = DEST / "upstream.json"
    if previous_path.exists():
        previous = json.loads(previous_path.read_text())
        if all(previous.get(k) == manifest[k] for k in ("sources", "rule_sha256", "dependencies")):
            print("CPA " + tag + ": matcher unchanged")
            return
    (DEST / "helps").mkdir(parents=True, exist_ok=True)
    (DEST / "config").mkdir(exist_ok=True)
    for path in (SOURCE, TEST):
        original = files[path]
        old = '"github.com/router-for-me/CLIProxyAPI/v8/internal/config"'
        if original.count(old) != 1:
            raise SystemExit("CPA import layout changed; inspect integration")
        data = original.replace(old, '"cliproxy-antigravity-acp/internal/cpacloak/config"')
        (DEST / "helps" / pathlib.PurePosixPath(path).name).write_text(data, encoding="utf-8", newline="\n")
    (DEST / "config/types.go").write_text(
        "// Code generated from CPA " + tag + "; DO NOT EDIT.\npackage config\n\n" + rule.group() + "\n",
        encoding="utf-8", newline="\n")
    (DEST / "version.go").write_text(
        "// Code generated by sync-cpa-cloak.py; DO NOT EDIT.\npackage cpacloak\n\n"
        + "const UpstreamTag = " + json.dumps(tag) + "\nconst UpstreamCommit = " + json.dumps(commit) + "\n",
        encoding="utf-8", newline="\n")
    (DEST / "LICENSE").write_text(files["LICENSE"], encoding="utf-8", newline="\n")
    previous_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print("Synced official CPA " + tag + " at " + commit)

if __name__ == "__main__":
    main()
